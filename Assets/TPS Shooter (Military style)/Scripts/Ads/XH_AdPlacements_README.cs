/// ============================================================================
/// XH-SDK 广告埋点 API 使用说明
/// ============================================================================
///
/// 本文件为 XH-SDK 广告系统的调用注释文档，方便快速浏览所有广告埋点。
/// 核心广告类位于: XH-SDK/Runtime/Minigame/API/AD/XH_AD.cs
/// 广告来源枚举: XH-SDK/Runtime/Minigame/API/AD/Const.cs (ESource 枚举)
///
/// ============================================================================
/// 一、插屏广告 (Interstitial Ad) — ShowInsert
/// ============================================================================
///
/// 调用方式: xh.api.Ad.ShowInsert("来源标识");
///
/// ┌─────────────────────────────────────────────────────────────────────┐
/// │ 场景点              │ 调用代码                                      │ 说明                  │
/// ├────────────────────┼──────────────────────────────────────────────┤──────────────────────┤
/// │ 点击"开始游戏"按钮  │ xh.api.Ad.ShowInsert("startgame");          │ 仅在点击开始时调用一次 │
/// │                     │                                              │ 建议在 Menu.OnPlay()   │
/// │                     │                                              │ 中触发                │
/// ├────────────────────┼──────────────────────────────────────────────┤──────────────────────┤
/// │ 首次进入游戏场景    │ xh.api.Ad.ShowInsert("first");              │ 进入游戏场景后调用一次 │
/// │                     │                                              │ 建议在 Scene 加载完毕后│
/// │                     │                                              │ 触发                  │
/// ├────────────────────┼──────────────────────────────────────────────┤──────────────────────┤
/// │ 游戏结算(胜/败)    │ xh.api.Ad.ShowInsert("settle");              │ 胜利或失败退出游戏时  │
/// │                     │ xh.api.Ad.ShowInsert("settle_win");        │ 调用一次              │
/// │                     │ xh.api.Ad.ShowInsert("settle_lose");        │                       │
/// │                     │                                              │ 建议在 Finish.Show()  │
/// │                     │                                              │ 中触发                │
/// ├────────────────────┼──────────────────────────────────────────────┤──────────────────────┤
/// │ 通用界面切换        │ xh.api.Ad.ShowInsert("common");             │ 每切换一次界面调用一次│
/// │                     │                                              │ 如: 武器选择→地图选择 │
/// │                     │                                              │ 地图选择→下载界面     │
/// ├────────────────────┼──────────────────────────────────────────────┤──────────────────────┤
/// │ 诡计宝箱(插屏类型)  │ xh.api.Ad.ShowInsert("common_box");         │ 误触型宝箱            │
/// │                     │                                              │ 关闭不影响正常游戏流程│
/// └────────────────────┴──────────────────────────────────────────────┴──────────────────────┘
///
/// 注意事项:
/// - 插屏广告内部有 CD(冷却时间)、频率控制，无需手动控制调用频率
/// - SDK 会自动根据线上配置决定是否真的展示广告
/// - 插屏失败时可自动降级为激励视频、原生插屏等（由线上配置控制）
/// - ESource 预定义来源: common, main, shop, battle, settle, load, setting,
///   stage_list, settle_win, settle_lose, first, launch, profile
///
/// ============================================================================
/// 二、激励视频广告 (Rewarded Video Ad) — ShowVideo
/// ============================================================================
///
/// 调用方式:
///   xh.api.Ad.ShowVideo("来源标识", onSuccess回调, onCancel回调);
///   或:
///   xh.api.Ad.ShowVideo("来源标识", onCloseWithResult回调);
///
/// onSuccess: 用户看完视频 → 给予奖励
/// onCancel:  用户中途关闭/加载失败 → 不给奖励
/// onCloseWithResult: bool参数, true=看完, false=未看完
///
/// ┌─────────────────────────────────────────────────────────────────────┐
/// │ 场景点              │ 说明                                        │
/// ├────────────────────┼──────────────────────────────────────────────┤
/// │ 复活/续命           │ 在玩家死亡时提供看广告复活的机会             │
/// │ 双倍奖励           │ 结算时看广告获得双倍金币/经验                 │
/// │ 解锁武器/地图       │ 看广告解锁锁定内容（需自行实现解锁系统）     │
/// │ 宝箱奖励           │ 诡计宝箱最终奖励（ShowTrickBoxOrVideo内部调用）│
/// └────────────────────┴──────────────────────────────────────────────┘
///
/// ============================================================================
/// 三、诡计宝箱+激励视频 (TrickBox or Rewarded Video) — ShowTrickBoxOrVideo
/// ============================================================================
///
/// 调用方式:
///   xh.api.Ad.ShowTrickBoxOrVideo("common_box", fun_success, fun_cancel);
///
/// 参数说明:
///   "common_box"  - 广告来源标识（字符串）
///   fun_success   - Action 回调，用户获得奖励时调用（看完视频或宝箱完成）
///   fun_cancel    - Action 回调，用户取消/关闭时调用（不给奖励）
///
/// ⚠️ 谨慎使用！必须搭配奖励机制。
///
/// 内部逻辑:
///   1. 检查线上配置是否启用宝箱模式 (CheckRewardBox)
///   2. 如果启用宝箱 → 显示诡计宝箱 UI（用户需多次点击关闭）
///      宝箱关闭后 → 弹出激励视频 → 看完才给奖励
///   3. 如果未启用宝箱 → 直接弹出激励视频 → 看完才给奖励
///
/// 诡计宝箱特点:
/// - 玩家需要点击多次才能关闭（默认5次，可通过线上配置 i_box_required_clicks 调整）
/// - 滑块会自动回落，制造"快关掉了"的错觉
/// - 横屏和竖屏有不同的交互方式（横屏直接点击，竖屏需同时点击左右按钮）
/// - 关闭宝箱后必须看完激励视频才能获得奖励
///
/// ============================================================================
/// 四、横幅广告 (Banner Ad) — ShowBanner / HideBanner
/// ============================================================================
///
/// 调用方式:
///   xh.api.Ad.ShowBanner("来源标识", 是否在顶部);
///   xh.api.Ad.HideBanner();       // 隐藏
///   xh.api.Ad.HideBanner(true);   // 隐藏并销毁
///
/// 说明:
/// - 通常在主界面、关卡列表等非战斗页面底部展示
/// - 进入战斗场景前建议调用 HideBanner()
/// - SDK 内部有自动刷新和切换逻辑 (i_ad_banner_switch_cd)
///
/// ============================================================================
/// 五、建议的广告埋点位置（基于本项目游戏流程）
/// ============================================================================
///
/// 游戏流程: 主菜单 → 武器选择 → 地图选择 → 下载 → 游戏战斗 → 结算
///
/// ┌──────────────────────────────────────────────────────────────────────────┐
/// │ 游戏节点          │ 建议埋点                          │ 对应脚本          │
/// ├───────────────────┼──────────────────────────────────────────────────────┤
/// │ 主菜单点击"Play"  │ xh.api.Ad.ShowInsert("startgame");                 │
/// │                   │                                    │ Menu.cs           │
/// ├───────────────────┼──────────────────────────────────────────────────────┤
/// │ 武器选择界面      │ xh.api.Ad.ShowBanner("shop");                      │
/// │                   │                                    │ WeaponChoose.cs  │
/// ├───────────────────┼──────────────────────────────────────────────────────┤
/// │ 地图选择界面      │ xh.api.Ad.ShowBanner("stage_list");                │
/// │                   │                                    │ LocationChoose.cs│
/// ├───────────────────┼──────────────────────────────────────────────────────┤
/// │ 进入游戏场景(首次)│ xh.api.Ad.ShowInsert("first");                     │
/// │                   │ xh.api.Ad.HideBanner();                             │
/// │                   │                                    │ GameManager.cs    │
/// ├───────────────────┼──────────────────────────────────────────────────────┤
/// │ 游戏结算(胜利)    │ xh.api.Ad.ShowInsert("settle_win");                │
/// │ 游戏结算(失败/死亡)│ xh.api.Ad.ShowInsert("settle");                   │
/// │                   │                                    │ Finish.cs        │
/// ├───────────────────┼──────────────────────────────────────────────────────┤
/// │ 返回主菜单        │ xh.api.Ad.ShowBanner("main");                      │
/// │                   │                                    │ Menu.cs           │
/// └───────────────────┴──────────────────────────────────────────────────────┘
///
